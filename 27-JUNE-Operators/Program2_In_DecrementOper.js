//Increment Operator
// ++ (Increment by 1)
/* Types: 1) Postfix (count++)
          2) Prifix (++count) */


// Postfix :  first print current value then increase by 1.
let count=5;
console.log(count++); // 5 
console.log(count); //6
console.log(count); // 6

//Prifix : first increase by 1 then print.
let count1=5;
console.log(++count1); //6

//Decrement Operator
// -- (decrease by 1)
/* Types : 1) Postfix (count--)
           2) Prifix (--count) */

// Postfix : Return first then decrease by 1.
let count2=5;
console.log(count2--); // 5 
console.log(count2); //4
console.log(count2); // 4

//Prifix : first increase by 1 then print.
let count3=5;
console.log(--count3); //4

// Example:
let a = 10;
console.log(a--);  // 10
console.log(--a);  // 8
console.log(--a);  // 7
console.log(a--);  // 7
console.log(--a);  // 5

         
