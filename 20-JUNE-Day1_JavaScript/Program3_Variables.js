//variables is a named container used to store values.
//Types of Variables
// var , let , const ;

// --------  1) var ---------
var city="Pune";
console.log(city);

var city="Goa";  // Redeclaration Allowed
console.log(city);

// --------- 2) let   ----------
let pythonBook="Python";
console.log(pythonBook);

let JavaScriptBook="JavaScript";
console.log(JavaScriptBook);

JavaScriptBook="TypeScript"; // Re-assigning a new Values.
console.log(JavaScriptBook);
console.log(JavaScriptBook);

//---------- 3) const -------------
// we can not Re-declare and Re-assign.
const PI = 3.14;
console.log(PI);


